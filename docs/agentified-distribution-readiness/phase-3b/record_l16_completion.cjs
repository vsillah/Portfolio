const { chromium } = require('playwright')
const fs = require('node:fs')
const path = require('node:path')
const { execFileSync } = require('node:child_process')

const revision = process.argv[2]
if (!/^[a-f0-9]{40}$/.test(revision || '')) throw new Error('Pass the reviewed commit SHA')
const output = path.resolve('agentified/workshop/l16-resting-card-review')
const candidate = path.resolve('agentified/workshop/phase-3b-review/L16/agentified-l16-resting-composite.mp4')
fs.mkdirSync(output, { recursive: true })

async function run() {
  const browser = await chromium.launch({ headless: true })
  try {
    for (const [name, width, height] of [['desktop', 1280, 720], ['mobile', 390, 844]]) {
      const context = await browser.newContext({ viewport: { width, height }, recordVideo: { dir: output, size: { width, height } } })
      const page = await context.newPage()
      await page.route('**/agentified-l16-illustrated-composite.mp4', route => {
        const bytes = fs.readFileSync(candidate)
        const range = route.request().headers().range?.match(/bytes=(\d+)-(\d*)/)
        if (!range) return route.fulfill({ body: bytes, contentType: 'video/mp4', headers: { 'Accept-Ranges': 'bytes' } })
        const start = Number(range[1])
        const end = range[2] ? Math.min(Number(range[2]), bytes.length - 1) : bytes.length - 1
        return route.fulfill({ status: 206, body: bytes.subarray(start, end + 1), contentType: 'video/mp4', headers: { 'Accept-Ranges': 'bytes', 'Content-Range': `bytes ${start}-${end}/${bytes.length}` } })
      })
      const url = `http://127.0.0.1:3108/agentified/learningplan?lesson=L16&rev=${revision}`
      await page.goto(url, { waitUntil: 'domcontentloaded' })
      await page.getByRole('heading', { name: 'Give the agent a job and a receipt' }).waitFor()
      await page.waitForTimeout(500)
      if (name === 'mobile') await page.getByRole('button', { name: 'Expand lesson navigation' }).click()
      await page.getByRole('button', { name: /L16: Audit the operating file/ }).click()
      await page.getByRole('heading', { name: 'Audit the operating file' }).waitFor()
      const video = page.locator('video')
      await video.waitFor()
      await page.waitForFunction(() => document.querySelector('video')?.readyState >= 1)
      await video.scrollIntoViewIfNeeded()
      const duration = await video.evaluate(element => element.duration)
      if (Math.abs(duration - 275.32) > .1) throw new Error(`${name}: candidate duration ${duration}`)
      await page.screenshot({ path: path.join(output, `${name}-setup.png`) })
      await page.getByRole('button', { name: 'English captions on' }).click()
      await page.getByText('Captions are off. Your place is saved with your workshop progress.').waitFor()
      await page.getByRole('button', { name: 'English captions off' }).click()
      await page.getByText('Captions are on. Your place is saved with your workshop progress.').waitFor()
      await page.getByRole('button', { name: 'Large captions' }).click()
      await page.getByRole('button', { name: 'Medium captions' }).click()
      await page.evaluate(() => { document.querySelector('video').currentTime = 266.5 })
      await page.waitForFunction(() => document.querySelector('video')?.currentTime >= 266.4)
      await page.screenshot({ path: path.join(output, `${name}-before-boundary.png`) })
      await video.evaluate(element => element.play())
      await page.waitForFunction(() => document.querySelector('video')?.currentTime >= 267.4)
      if (await page.getByRole('status', { name: 'L16 complete. Agentified course complete.' }).count()) throw new Error(`${name}: early overlay`)
      await page.screenshot({ path: path.join(output, `${name}-resting-card.png`) })
      await page.waitForFunction(() => document.querySelector('video')?.ended, { timeout: 15000 })
      const overlay = page.getByRole('status', { name: 'L16 complete. Agentified course complete.' })
      await overlay.waitFor()
      if (await overlay.count() !== 1) throw new Error(`${name}: duplicate overlay`)
      await page.waitForTimeout(500)
      await page.screenshot({ path: path.join(output, `${name}-complete.png`) })
      await video.evaluate(element => { element.currentTime = 266; return element.play() })
      await page.waitForFunction(() => document.querySelector('video')?.currentTime >= 266)
      await overlay.waitFor({ state: 'hidden' })
      await page.screenshot({ path: path.join(output, `${name}-replay.png`) })
      await video.evaluate(element => element.pause())
      await context.close()
      const webm = await page.video().path()
      const mp4 = path.join(output, `${name}-walkthrough.mp4`)
      execFileSync('ffmpeg', ['-y', '-hide_banner', '-loglevel', 'error', '-i', webm, '-c:v', 'libx264', '-crf', '22', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', mp4])
      fs.unlinkSync(webm)
      execFileSync('ffmpeg', ['-v', 'error', '-i', mp4, '-f', 'null', '-'])
      console.log(JSON.stringify({ name, url, loadedLesson: 'L16', candidateDuration: duration, mp4 }))
    }
  } finally { await browser.close() }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
