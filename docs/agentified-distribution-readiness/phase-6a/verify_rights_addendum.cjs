const fs = require('node:fs')
const crypto = require('node:crypto')
const assert = require('node:assert/strict')
const hash = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex')
const receipt = require('./l02-l04-owner-rights-addendum-2026-11-23.json')
const source = fs.readFileSync(receipt.source.path)
const content = JSON.parse(source)
assert.equal(receipt.productionCommit, 'aef8c3ec2a3415f0c84f21cfbd3f143c1a299f85')
assert.equal(hash(source), receipt.source.sha256)
assert.equal(content.version, receipt.source.version)
assert.deepEqual(receipt.coveredAssets.map((item) => item.lessonId), ['L02', 'L03', 'L04'])
for (const record of receipt.coveredAssets) {
  const lesson = content.lessons.find((item) => item.id === record.lessonId)
  assert.ok(lesson)
  assert.equal(lesson.title, record.lessonTitle)
  assert.equal(hash(JSON.stringify(lesson)), record.lessonRecordSha256)
  assert.deepEqual(lesson.visuals.map((item) => `public${item.src}`), [record.diagram.path])
  assert.equal(hash(fs.readFileSync(record.diagram.path)), record.diagram.sha256)
}
console.log('PASS: L02-L04 rights addendum matches exact production content and diagrams')
