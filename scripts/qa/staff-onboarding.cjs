// Local-only rendered verification and privacy-safe recording; no real credentials required.
const { chromium } = require('playwright')
const fs = require('node:fs/promises')
const assert = require('node:assert/strict')
const path = require('node:path')
const base = process.env.STAFF_GUIDE_QA_URL || 'http://127.0.0.1:3217'
if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(base)) throw new Error('Local preview only')
const out = path.resolve('docs/staff-onboarding-qa')
const sections = ['business-map', 'workday', 'boundaries', 'first-week', 'tool-map', 'help-glossary']
;(async () => {
  await fs.mkdir(out, { recursive: true })
  const browser = await chromium.launch({ headless: true })
  const results = []
  const errors = []
  const blocked = []
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, recordVideo: { dir: path.join(out, 'raw'), size: { width: 1440, height: 1000 } } })
  await context.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : (blocked.push(new URL(route.request().url()).origin), route.abort()))
  const page = await context.newPage()
  page.on('pageerror', error => errors.push(error.message))
  for (const width of [1440, 360, 390, 430, 768]) {
    await page.setViewportSize({ width, height: width < 500 ? 844 : 1000 })
    await page.goto(`${base}/help/staff`)
    await page.getByRole('heading', { level: 1 }).waitFor()
    await page.evaluate(() => document.fonts.ready)
    await page.screenshot({ path: path.join(out, `welcome-${width}.png`), fullPage: true })
    await page.waitForTimeout(900)
    await page.getByRole('link', { name: /Start your first week/ }).click()
    await page.waitForFunction(() => document.querySelector('#first-week').open)
    const check = page.getByRole('checkbox', { name: /Day 1: Confirm your supervisor/ })
    await check.check()
    assert(await check.isChecked())
    await page.screenshot({ path: path.join(out, `checklist-${width}.png`) })
    await check.uncheck()
    for (const section of sections) {
      const detail = page.locator(`#${section}`)
      if (!(await detail.getAttribute('open') !== null)) await detail.locator('summary').click()
      await detail.scrollIntoViewIfNeeded()
      const overflow = await page.evaluate(() => [...document.querySelectorAll('article *')].filter(el => el.getClientRects().length && (el.getBoundingClientRect().right > innerWidth + 1 || el.getBoundingClientRect().left < -1)).map(el => el.tagName + ':' + el.textContent.slice(0, 40)))
      assert.deepEqual(overflow, [], `Overflow at ${width} / ${section}`)
      if (['business-map', 'workday', 'tool-map', 'boundaries'].includes(section)) await page.screenshot({ path: path.join(out, `${section}-${width}.png`) })
      await page.waitForTimeout(500)
      await detail.locator('summary').click()
    }
    results.push({ width, sections: 6, overflow: false, checklist: 'pass' })
  }
  await page.goto(`${base}/help/staff#tool-map`)
  await page.waitForFunction(() => document.querySelector('#tool-map').open)
  await page.reload()
  await page.waitForFunction(() => document.querySelector('#tool-map').open)
  await page.getByRole('link', { name: '← Help center' }).click()
  await page.waitForURL('**/help')
  await page.getByRole('link', { name: /Joining the team/ }).click()
  await page.waitForURL('**/help/staff')
  await page.getByRole('link', { name: 'Print / Save as PDF' }).click()
  await page.waitForURL('**/help/staff/print')
  assert.equal(await page.locator('article details').count(), 0)
  assert.equal(await page.locator('article input[type=checkbox]').count(), 15)
  // Verify the visible print button invokes the native print action without a remote exporter.
  await page.evaluate(() => { window.__printed = false; window.print = () => { window.__printed = true } })
  await page.getByRole('button', { name: 'Print / Save as PDF' }).click()
  assert(await page.evaluate(() => window.__printed))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.emulateMedia({ media: 'print' })
  await page.screenshot({ path: path.join(out, 'print-preview.png') })
  await page.pdf({ path: path.join(out, 'staff-guide.pdf'), format: 'A4', printBackground: true, preferCSSPageSize: true })
  const printText = await page.locator('article').innerText()
  for (const term of ['Supabase', 'Telnyx', 'Jev', 'Words you will see', 'Technical operator']) assert(printText.includes(term))
  await page.emulateMedia({ media: 'screen' })
  await page.getByRole('link', { name: '← Interactive guide' }).click()
  await page.waitForURL('**/help/staff')
  // Check both themes explicitly; the default follows the browser/system preference.
  await page.evaluate(() => document.documentElement.classList.remove('dark'))
  await page.screenshot({ path: path.join(out, 'welcome-light-1440.png'), fullPage: true })
  await page.evaluate(() => document.documentElement.classList.add('dark'))
  await page.screenshot({ path: path.join(out, 'welcome-dark-1440.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: path.join(out, 'welcome-dark-390.png'), fullPage: true })
  await page.locator('#help-glossary summary').click()
  await page.getByRole('link', { name: 'Operator procedures (admin access required)' }).click()
  await page.waitForURL('**/auth/login?redirect=*')
  assert(new URL(page.url()).searchParams.get('redirect') === '/admin/help')
  assert.deepEqual(errors, [])
  await context.close()
  await browser.close()
  await fs.writeFile(path.join(out, 'results.json'), JSON.stringify({ route: `${base}/help/staff`, results, deepLinkReload: 'pass', helpNavigation: 'pass', adminAccessGate: 'pass', printRoute: 'pass', browserErrors: errors, externalOriginsBlocked: [...new Set(blocked)] }, null, 2))
  console.log(JSON.stringify({ results, errors, out }))
})().catch(error => { console.error(error); process.exit(1) })
