import { chromium } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'
import { execFileSync } from 'node:child_process'
import { seedSession, installSafeRoutes } from './record-warm-planned-draft-actions-qa.mjs'
const base = process.env.QA_BASE_URL || 'http://127.0.0.1:3117'
const output = `${process.cwd()}/docs/warm-outreach-qa/warm-outbound-completion`
await mkdir(output, { recursive: true })
const browser = await chromium.launch()
const runs = []
for (const width of [1440, 768, 390]) {
  const context = await browser.newContext({ viewport: { width, height: 900 }, recordVideo: { dir: `${output}/source`, size: { width, height: 900 } } })
  const page = await context.newPage()
  const externalRequests = [], localRequests = []
  await seedSession(page)
  await installSafeRoutes(page, externalRequests, localRequests)
  await page.route('**/api/admin/social-content/calendar?*', route => route.fulfill({ json: { items: [{
    id: 'calendar-qa-1', campaign_id: 'campaign-qa', title: 'Workshop proof milestone', planned_angle: 'Approved workshop source',
    scheduled_for: '2026-10-15T14:00:00.000Z', campaign_phase: 'proof', channel: 'linkedin', authorization_status: 'authorized', due_status: 'planned',
    attraction_campaigns: { status: 'active', name: 'Synthetic workshop campaign' },
  }] } }))
  const queue = { id: 'qa-outreach-queue-existing-101', contactSubmissionId: 101, channel: 'email', status: 'rejected', body: 'Draft direction: follow up via email. Safe mention: workshop.', subject: 'Workshop follow-up', createdAt: '2026-09-08T12:00:00Z', updatedAt: '2026-09-08T12:00:00.000Z', generationInputs: {} }
  await page.route('**/api/admin/outreach/drafts/*/inputs', route => route.fulfill({ json: queue }))
  await page.route('**/api/admin/outreach', async route => {
    if (route.request().method() !== 'PATCH') return route.fallback()
    const { action, updates, expectedVersions } = route.request().postDataJSON()
    if (expectedVersions?.[queue.id] !== queue.updatedAt) return route.fulfill({ status: 409, json: { error: 'Fixture version conflict' } })
    queue.updatedAt = new Date(Date.parse(queue.updatedAt) + 1).toISOString()
    Object.assign(queue, action === 'edit' ? updates : {}, { status: action === 'approve' ? 'approved' : action === 'reject' ? 'rejected' : 'draft' })
    localRequests.push({ method: 'PATCH', pathname: '/api/admin/outreach', fixture: true })
    await route.fulfill({ json: { message: 'Copy saved. Review required again.', versions: { [queue.id]: queue.updatedAt } } })
  })
  await page.goto(`${base}/admin/outreach?tab=leads&filter=warm&view=planning&qa=warm-planning-backlog`, { waitUntil: 'networkidle' })
  await page.getByLabel('Warm outreach planning backlog').waitFor({ timeout: 30000 })
  await page.getByRole('link', { name: 'Calendar source needed' }).scrollIntoViewIfNeeded()
  await page.waitForTimeout(1500)
  await page.getByLabel('Campaign milestone').selectOption('calendar-qa-1')
  await page.getByRole('link', { name: 'Open calendar source' }).waitFor()
  await page.waitForTimeout(1500)
  await page.getByLabel('Warm planning campaign context').screenshot({ path: `${output}/calendar-${width}.png` })
  await page.goto(`${base}/admin/outreach?tab=leads&filter=warm&id=101&contactId=101&draftReview=qa-outreach-queue-existing-101#warm-gmail-draft-review`, { waitUntil: 'networkidle' })
  const panel = page.getByLabel('Gmail draft review for Amina Batchready')
  await panel.waitFor({ timeout: 30000 })
  await panel.scrollIntoViewIfNeeded()
  await page.waitForTimeout(1500)
  await panel.getByRole('button', { name: 'Write final copy' }).click()
  await panel.getByLabel('Final message').fill('Hi Amina, thanks for discussing the workshop. Would Tuesday work for a short follow-up?')
  await page.waitForTimeout(1500)
  await panel.evaluate(element => element.scrollIntoView({ block: 'start' }))
  await page.waitForTimeout(400)
  await panel.screenshot({ path: `${output}/editor-${width}.png` })
  await panel.getByRole('button', { name: 'Save and return to review' }).click()
  await panel.getByRole('button', { name: 'Edit final copy' }).waitFor()
  await panel.getByText('Copy saved. Review required again.').waitFor()
  await panel.getByText('Reject draft', { exact: true }).click()
  await panel.getByLabel('Feedback (optional)').fill('Make the proposed next step more specific.')
  await panel.getByRole('button', { name: 'Confirm rejection' }).click()
  await panel.getByRole('button', { name: 'Revise rejected draft' }).waitFor()
  await page.waitForTimeout(1500)
  await panel.getByRole('button', { name: 'Revise rejected draft' }).click()
  await panel.getByLabel('Final message').fill('Hi Amina, thanks for discussing the workshop. Would Tuesday at 2 work for a short follow-up?')
  await panel.getByRole('button', { name: 'Save and return to review' }).click()
  await page.waitForTimeout(1500)
  await panel.getByRole('button', { name: 'Approve final copy' }).click()
  await panel.getByText('Final copy approved. Mailbox draft and send require their separate gates.').waitFor()
  await page.waitForTimeout(1800)
  await panel.evaluate(element => element.scrollIntoView({ block: 'start' }))
  await page.waitForTimeout(400)
  await panel.screenshot({ path: `${output}/review-${width}.png` })
  await page.goto(`${base}/admin/outreach?tab=leads&filter=warm&id=103&contactId=103#warm-manual-social-handoff`, { waitUntil: 'networkidle' })
  const manual = page.getByTestId('warm-manual-social-handoff').first()
  await manual.waitFor({ timeout: 15000 })
  const manualText = manual.getByLabel('LinkedIn manual handoff text')
  await manualText.fill('Draft direction: follow up. Safe mention: workshop.')
  if (!await manual.getByRole('button', { name: 'Copy LinkedIn text' }).isDisabled()) throw new Error('Planner text reached manual clipboard gate')
  await manual.evaluate(element => element.scrollIntoView({ block: 'start' }))
  await page.waitForTimeout(1500)
  await manualText.fill('Hi Nia, would Tuesday suit our workshop follow-up?')
  if (!await manual.getByRole('button', { name: 'Copy LinkedIn text' }).isEnabled()) throw new Error('Valid manual copy cannot proceed')
  await page.waitForTimeout(1500)
  await manual.evaluate(element => element.scrollIntoView({ block: 'start' }))
  await page.waitForTimeout(400)
  await manual.screenshot({ path: `${output}/manual-${width}.png` })
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
  if (overflow || externalRequests.length) throw new Error(JSON.stringify({ width, overflow, externalRequests }))
  const video = page.video()
  await context.close()
  const raw = await video.path()
  execFileSync('ffmpeg', ['-y', '-i', raw, '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', `${output}/walkthrough-${width}.mp4`], { stdio: 'pipe' })
  runs.push({ width, overflow, externalRequests, localRequests, persistence: 'synthetic HTTP fixture; server contract verified separately by Vitest' })
}
await browser.close()
await writeFile(`${output}/receipt.json`, JSON.stringify({ runs }, null, 2))
console.log(output)
